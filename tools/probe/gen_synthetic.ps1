<#
.SYNOPSIS
  Writes a synthetic .ll of about -Lines lines (many small functions) to time the IR -> exe pipeline.
.DESCRIPTION
  Each function f_N takes two i32, does a few arithmetic ops, calls f_(N-1) (f_0 is a leaf) and returns
  an i32; main calls every function in a loop and prints a checksum, so the exe can be run to check
  the result (-O0 and -O2 must agree). With -DebugInfo every function gets a DISubprogram and every
  instruction a DILocation (one line = one "node"), which is what the IDE's Debug builds will carry.
.EXAMPLE
  powershell -File tools\probe\gen_synthetic.ps1 -Lines 2000 -Out tools\probe\out\synth2000.ll -DebugInfo
#>
param(
  [int]$Lines = 2000,
  [Parameter(Mandatory = $true)][string]$Out,
  [switch]$DebugInfo
)
$ErrorActionPreference = 'Stop'
$sb = New-Object System.Text.StringBuilder
$meta = New-Object System.Text.StringBuilder
function L([string]$s) { [void]$sb.AppendLine($s) }
$bodyLinesPerFn = 9       # define + 7 instructions + close brace
$metaLinesPerFn = 7       # DISubprogram + 6 DILocations
$perFn = $bodyLinesPerFn
if ($DebugInfo) { $perFn += $metaLinesPerFn }
$header = 12; $mainLines = 22; $footer = 10
$n = [Math]::Max(2, [int](($Lines - $header - $mainLines - $footer) / $perFn))

L "; synthetic.ll - generated by gen_synthetic.ps1 ($n functions, debug info: $DebugInfo)"
L 'source_filename = "synthetic.ll"'
L 'target datalayout = "e-m:w-p270:32:32-p271:32:32-p272:64:64-i64:64-i128:128-f80:128-n8:16:32:64-S128"'
L 'target triple = "x86_64-w64-windows-gnu"'
L ''
L '@.fmt = private unnamed_addr constant [15 x i8] c"checksum=%08x\0A\00", align 1'
L 'declare dso_local i32 @printf(ptr, ...)'
L ''
$mid = 100  # metadata ids start here; 0..99 reserved for the CU and types
$dbgIdx = $mid
function Dbg([string]$suffix) { if ($DebugInfo) { return ", !dbg !$suffix" } else { return '' } }
for ($k = 0; $k -lt $n; $k++) {
  $sp = $dbgIdx; $dbgIdx++
  $locs = @(); for ($j = 0; $j -lt 6; $j++) { $locs += $dbgIdx; $dbgIdx++ }
  $def = "define dso_local i32 @f_$k(i32 %a, i32 %b) #0"
  if ($DebugInfo) { $def += " !dbg !$sp" }
  $def += ' {'
  $defLine = $sb.ToString().Split("`n").Length
  L $def
  L "  %t0 = add nsw i32 %a, %b$(Dbg $locs[0])"
  L "  %t1 = mul nsw i32 %t0, $(($k % 13) + 1)$(Dbg $locs[1])"
  L "  %t2 = xor i32 %t1, $(($k * 2654435761) % 65536)$(Dbg $locs[2])"
  if ($k -eq 0) { L "  %t3 = lshr i32 %t2, 1$(Dbg $locs[3])" }
  else { L "  %t3 = call i32 @f_$($k - 1)(i32 %t2, i32 %a)$(Dbg $locs[3])" }
  L "  %t4 = sub nsw i32 %t3, %b$(Dbg $locs[4])"
  L "  %t5 = add nsw i32 %t4, %t2$(Dbg $locs[4])"
  L "  ret i32 %t5$(Dbg $locs[5])"
  L '}'
  if ($DebugInfo) {
    [void]$meta.AppendLine("!$sp = distinct !DISubprogram(name: `"f_$k`", scope: !1, file: !1, line: $defLine, type: !7, scopeLine: $defLine, flags: DIFlagPrototyped, spFlags: DISPFlagDefinition, unit: !0)")
    for ($j = 0; $j -lt 6; $j++) { [void]$meta.AppendLine("!$($locs[$j]) = !DILocation(line: $($defLine + 1 + $j), column: 1, scope: !$sp)") }
  }
}
# main: call every function 1000 times, fold into a checksum
L ''
L 'define dso_local i32 @main() #0 {'
L 'entry:'
L '  br label %loop'
L 'loop:'
L '  %i = phi i32 [ 0, %entry ], [ %i.next, %loop ]'
L '  %acc = phi i32 [ 0, %entry ], [ %acc.next, %loop ]'
L "  %r = call i32 @f_$($n - 1)(i32 %i, i32 %acc)"
L '  %acc.rot = shl i32 %acc, 5'
L '  %acc.mix = xor i32 %acc.rot, %r'
L '  %acc.next = add i32 %acc.mix, %i'
L '  %i.next = add nsw i32 %i, 1'
L '  %again = icmp slt i32 %i.next, 1000'
L '  br i1 %again, label %loop, label %done'
L 'done:'
L '  %c = call i32 (ptr, ...) @printf(ptr @.fmt, i32 %acc.next)'
L '  ret i32 0'
L '}'
L ''
L 'attributes #0 = { nounwind uwtable "target-cpu"="x86-64" }'
if ($DebugInfo) {
  L ''
  L '!llvm.dbg.cu = !{!0}'
  L '!llvm.module.flags = !{!2, !3, !4}'
  L '!0 = distinct !DICompileUnit(language: DW_LANG_C99, file: !1, producer: "treadle synthetic", isOptimized: false, runtimeVersion: 0, emissionKind: FullDebug, splitDebugInlining: false, nameTableKind: None)'
  $full = $Out
  if (-not [IO.Path]::IsPathRooted($full)) { $full = Join-Path (Get-Location).Path $full }
  $full = [IO.Path]::GetFullPath($full)
  L "!1 = !DIFile(filename: `"$([IO.Path]::GetFileName($full))`", directory: `"$((Split-Path $full -Parent).Replace('\', '/'))`")"
  L '!2 = !{i32 7, !"Dwarf Version", i32 4}'
  L '!3 = !{i32 2, !"Debug Info Version", i32 3}'
  L '!4 = !{i32 7, !"uwtable", i32 2}'
  L '!6 = !DIBasicType(name: "int", size: 32, encoding: DW_ATE_signed)'
  L '!7 = !DISubroutineType(types: !8)'
  L '!8 = !{!6, !6, !6}'
  [void]$sb.Append($meta.ToString())
}
$dir = Split-Path $Out -Parent
if ($dir) { New-Item -ItemType Directory -Force $dir | Out-Null }
[IO.File]::WriteAllText($Out, $sb.ToString(), (New-Object System.Text.UTF8Encoding $false))
$count = ($sb.ToString() -split "`n").Length
Write-Host "wrote $Out : $n functions, $count lines, $((Get-Item $Out).Length) bytes"
