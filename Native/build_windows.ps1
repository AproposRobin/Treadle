<#
Builds Native/bin/win64/treadlehost.dll (+ treadlehost.lib, treadlehost.def) on Windows with the portable llvm-mingw
toolchain: the Treadle native host (SDL2 + OpenGL3 + Dear ImGui + imnodes + cimgui + cimnodes + host\treadlehost.cpp).
Toolchain (as last used): llvm-mingw 20261006 ucrt-x86_64 (clang 23.1.3, lld, libc++), from
  https://github.com/mstorsjo/llvm-mingw/releases  (sha256 317492c456aa27ee607a5919f1d2d38dcdc1112516a24d0bf4b00d078f52d17a)
found through $env:TREADLE_LLVM (an llvm-mingw root), else tools\llvm-mingw of the repository
  (scripts\get-llvm-mingw.ps1). SDL2 2.32.10 mingw devel build
  (SDL2-devel-2.32.10-mingw.zip from libsdl-org/SDL, sha256
  f15cff5fca62ec9381a016ef1d42a95c638cd72d2f226ba5781c76fe43dbd1ac): $env:SDL2_MINGW, its x86_64-w64-mingw32
  folder; else $env:TREADLE_SDL2 (the package root), else tools\SDL2-2.32.10 of the repository
  (scripts\get-sdl2.ps1).
SDL2 and the C++ runtime are linked statically; only system DLLs remain as imports. The host's own exports carry the
th_ prefix (Native/src/ImNodes.bf binds them). The window icon comes from host\treadle_icon.h (generated by
packaging\treadle-icon\make-icon-header.ps1), the DLL's icon resource from packaging\treadle-icon\Treadle.ico.
The DLL carries a VERSIONINFO resource (Native\host\treadlehost.rc, compiled with llvm-windres): product
"Treadle host", the host's own version 1.1.0.0 (host contract 1, independent of the editor version), company and
copyright from NOTICE, which the script writes into obj\win64\treadleversion.h before it compiles the resource.
Reproducible: the same sources and toolchain give the same bytes (no link time in the PE header, __FILE__ paths
relative to the repository, no date or time macros). The script prints the sha256 of the DLL and the import
library and compares them with packaging\host-sha256.txt; record the new hashes there when the host changes.
Usage: powershell -File Native\build_windows.ps1 [-Clean]
The older Native/build_windows_mingw.sh (MSYS/Linux mingw-w64 g++) still builds the same exports (no VERSIONINFO,
not reproducible).
#>
param([switch]$Clean)
$ErrorActionPreference = 'Stop'
$here = $PSScriptRoot
$root = Split-Path $here -Parent
$mingw = if ($env:TREADLE_LLVM) { $env:TREADLE_LLVM } else { Join-Path $root 'tools\llvm-mingw' }
if (-not (Test-Path (Join-Path $mingw 'bin\clang++.exe'))) {
  throw "llvm-mingw not found at '$mingw'. Set TREADLE_LLVM to an llvm-mingw root (see the header of this script)."
}
$sdlPkg = if ($env:TREADLE_SDL2) { $env:TREADLE_SDL2 } else { Join-Path $root 'tools\SDL2-2.32.10' }
$sdl = if ($env:SDL2_MINGW) { $env:SDL2_MINGW } else { Join-Path $sdlPkg 'x86_64-w64-mingw32' }
if (-not (Test-Path (Join-Path $sdl 'lib\libSDL2.a'))) {
  throw "SDL2 mingw devel not found at '$sdl'. Set SDL2_MINGW to its x86_64-w64-mingw32 folder (see the header of this script)."
}
$bin = Join-Path $mingw 'bin'
$cxx = Join-Path $bin 'clang++.exe'
$T = Join-Path $here 'third_party'
$out = Join-Path $here 'bin\win64'
$obj = Join-Path $here 'obj\win64'
New-Item -ItemType Directory -Force $out, $obj | Out-Null
if ($Clean) { Get-ChildItem $obj -Filter *.o | Remove-Item }

# VERSIONINFO inputs: the copyright holder and line from NOTICE (the exe takes them from the same file via
# BeefProj's [Platform.Windows]). The host's own version is in Native\host\treadlehost.rc.
$noticeText = [IO.File]::ReadAllText((Join-Path $root 'NOTICE'))
if ($noticeText -notmatch '(?m)^(Copyright\s+\d{4}\s+.+?)\s*$') { throw 'NOTICE has no Copyright line' }
$copyrightLine = $Matches[1]
$holder = $copyrightLine -replace '^Copyright\s+\d{4}\s+', ''
$gen = @(
  "/* Generated by Native\build_windows.ps1 from NOTICE. Do not edit. */",
  "#define TH_COMPANY `"$holder`"",
  "#define TH_COPYRIGHT `"$copyrightLine`""
)
Set-Content -Path (Join-Path $obj 'treadleversion.h') -Value $gen -Encoding ascii
$srcs = @(
  'cimgui\imgui\imgui.cpp','cimgui\imgui\imgui_draw.cpp','cimgui\imgui\imgui_tables.cpp','cimgui\imgui\imgui_widgets.cpp',
  'cimgui\imgui\imgui_demo.cpp','cimgui\imgui\imgui_impl_sdl2.cpp','cimgui\imgui\imgui_impl_opengl3.cpp',
  'cimgui\cimgui.cpp','cimnodes\imnodes\imnodes.cpp','cimnodes\cimnodes.cpp') | ForEach-Object { Join-Path $T $_ }
$srcs += Join-Path $here 'host\treadlehost.cpp'
# Embedded __FILE__ strings (ImGui asserts) name the source relative to the repository, not the build machine.
$flags = @('-O2','-DNDEBUG','-DIMNODES_NAMESPACE=imnodes','-DSDL_MAIN_HANDLED',"-ffile-prefix-map=$root=.","-ffile-prefix-map=$($root.Replace([char]92,[char]47))=.","-I$T\cimgui\imgui","-I$T\cimgui","-I$T\cimnodes\imnodes","-I$sdl\include\SDL2")
$objs = @()
foreach ($s in $srcs) {
  $o = Join-Path $obj (([IO.Path]::GetFileNameWithoutExtension($s)) + '.o')
  if (-not (Test-Path $o) -or (Get-Item $s).LastWriteTime -gt (Get-Item $o).LastWriteTime) {
    Write-Host "  CXX $s"
    & $cxx @flags -c $s -o $o
    if ($LASTEXITCODE) { throw "compile failed: $s" }
  }
  $objs += $o
}
# VERSIONINFO resource (Native\host\treadlehost.rc + the generated treadleversion.h), rebuilt every run.
$resObj = Join-Path $obj 'treadlehost.res.o'
& (Join-Path $bin 'llvm-windres.exe') -I $obj -I (Join-Path $here 'host') -I (Join-Path $root 'packaging\treadle-icon') -O coff (Join-Path $here 'host\treadlehost.rc') -o $resObj
if ($LASTEXITCODE) { throw 'windres failed: host\treadlehost.rc' }
$objs += $resObj
$libs = @('-lopengl32','-lsetupapi','-lwinmm','-limm32','-lversion','-lole32','-loleaut32','-lgdi32','-luser32','-lshell32','-luuid','-ladvapi32','-lcfgmgr32')
# --no-insert-timestamp: no link time in the PE header, so a rebuild gives the same bytes.
& $cxx -shared -o "$out\treadlehost.dll" @objs "-Wl,--output-def,$out\treadlehost.def" '-Wl,--no-insert-timestamp' -s -static "$sdl\lib\libSDL2.a" @libs
if ($LASTEXITCODE) { throw 'link failed' }
# The editor's GPU-preference exports (host\gpu_preference.c): an MSVC-target object file the editor links
# (TreadleEditor\BeefProj.toml), because the drivers need the values as initialised data in Treadle.exe.
& (Join-Path $bin 'clang.exe') --target=x86_64-pc-windows-msvc -O2 -mno-incremental-linker-compatible -c (Join-Path $here 'host\gpu_preference.c') -o "$out\gpu_preference.obj"
if ($LASTEXITCODE) { throw 'compile failed: host\gpu_preference.c' }
# MSVC-compatible import library so Beef (lld-link) can link against the DLL.
& (Join-Path $bin 'llvm-dlltool.exe') -m i386:x86-64 -d "$out\treadlehost.def" -D treadlehost.dll -l "$out\treadlehost.lib"
if ($LASTEXITCODE) { throw 'dlltool failed' }
Write-Host "Built $out\treadlehost.dll + treadlehost.lib"
# The sha256 of what was built, against the recorded ones (packaging\host-sha256.txt, sha256sum format).
$recorded = @{}
$hashFile = Join-Path $root 'packaging\host-sha256.txt'
if (Test-Path $hashFile) {
  foreach ($line in Get-Content $hashFile) { if ($line -match '^([0-9a-f]{64}) [ *](\S+)$') { $recorded[$Matches[2]] = $Matches[1] } }
}
foreach ($f in 'treadlehost.dll', 'treadlehost.lib') {
  $h = (Get-FileHash -Algorithm SHA256 (Join-Path $out $f)).Hash.ToLowerInvariant()
  $rel = "Native/bin/win64/$f"
  $note = if (-not $recorded.ContainsKey($rel)) { 'not recorded' } elseif ($recorded[$rel] -eq $h) { 'matches packaging\host-sha256.txt' } else { 'DIFFERS from packaging\host-sha256.txt' }
  Write-Host "$h  $rel  ($note)"
}
