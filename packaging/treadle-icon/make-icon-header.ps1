<#
.SYNOPSIS
  Writes Native\host\treadle_icon.h: the pixels of Treadle-64.png as a 64 x 64 RGBA byte array, which the native
  host hands to SDL_SetWindowIcon (the window icon on Windows, X11 and Wayland). Re-run it after make-icon.ps1.
  The output is deterministic (same PNG, same bytes), so the host build stays reproducible.
#>
param([string]$Png = "", [string]$Out = "")
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
if (-not $Png) { $Png = Join-Path $PSScriptRoot "Treadle-64.png" }
if (-not $Out) { $Out = Join-Path $root "Native\host\treadle_icon.h" }
Add-Type -AssemblyName System.Drawing
$bmp = New-Object System.Drawing.Bitmap $Png
try {
    $w = $bmp.Width; $h = $bmp.Height
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.Append("// Generated by packaging/treadle-icon/make-icon-header.ps1 from Treadle-64.png; do not edit.`n")
    [void]$sb.Append("// The window icon: ${w} x ${h} pixels, 8-bit R, G, B, A per pixel, rows top to bottom.`n")
    [void]$sb.Append("#pragma once`n`n")
    [void]$sb.Append("static const int kTreadleIconWidth = $w;`nstatic const int kTreadleIconHeight = $h;`n")
    [void]$sb.Append("static const unsigned char kTreadleIconRGBA[$($w * $h * 4)] = {`n")
    for ($y = 0; $y -lt $h; $y++) {
        $row = New-Object System.Collections.Generic.List[string]
        for ($x = 0; $x -lt $w; $x++) {
            $c = $bmp.GetPixel($x, $y)
            $row.Add("$($c.R),$($c.G),$($c.B),$($c.A)")
        }
        [void]$sb.Append("`t" + ($row -join ",") + ",`n")
    }
    [void]$sb.Append("};`n")
    [IO.File]::WriteAllText($Out, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
    Write-Output "wrote $Out (${w}x${h})"
} finally { $bmp.Dispose() }
